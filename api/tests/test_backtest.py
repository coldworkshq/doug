from magpie.backtest.curve import capture_curve, rule_stats
from magpie.backtest.harvest import HarvestedPR
from magpie.backtest.label import label_defects
from magpie.backtest.replay import to_metadata


def _pr(number: int, title: str = "t", body: str = "", **kw) -> HarvestedPR:
    base = dict(
        number=number,
        title=title,
        body=body,
        author="dev",
        author_is_bot=False,
        additions=10,
        deletions=2,
        files=["src/a.py"],
        created_at="2026-01-01 10:00:00+00:00",
        merged_at="2026-01-02 10:00:00+00:00",
        approvals=1,
        first_approval_at="2026-01-01 11:30:00+00:00",
    )
    base.update(kw)
    return HarvestedPR.model_validate(base)


# --- labeling ---------------------------------------------------------------


def test_github_autogenerated_revert_body():
    prs = [_pr(100, title="Add caching"), _pr(101, title="Revert PR", body="Reverts acme/app#100")]
    assert label_defects(prs) == {100}


def test_revert_reference_in_title():
    prs = [_pr(7, title="Ship feature"), _pr(9, title="Revert #7, broke prod")]
    assert label_defects(prs) == {7}


def test_quoted_title_revert_without_number():
    prs = [_pr(40, title="Add rate limiter"), _pr(44, title='Revert "Add rate limiter"')]
    assert label_defects(prs) == {40}


def test_mention_without_revert_does_not_label():
    prs = [_pr(1, title="Add x"), _pr(2, title="Follow-up", body="Similar to #1")]
    assert label_defects(prs) == set()


def test_reference_outside_harvest_window_ignored():
    prs = [_pr(50, title="Revert old change", body="Reverts acme/app#3")]
    assert label_defects(prs) == set()


# --- replay mapping ---------------------------------------------------------


def test_approval_latency_computed_from_timestamps():
    meta = to_metadata(_pr(1))
    assert meta.approval_latency_s == 90 * 60


def test_unapproved_pr_has_no_latency():
    meta = to_metadata(_pr(1, approvals=0, first_approval_at=None))
    assert meta.approval_latency_s is None


def test_bot_author_mapped_to_agent():
    meta = to_metadata(_pr(1, author_is_bot=True))
    assert meta.author_type == "agent"


def test_module_recency_never_guessed():
    assert to_metadata(_pr(1)).days_since_last_human_commit is None


# --- curve math -------------------------------------------------------------


def test_perfect_separation():
    scored = [(0.9, True), (0.8, True), (0.1, False), (0.1, False)]
    c = capture_curve(scored)
    assert c.capture_at(0.5) == 1.0
    # Max attainable AUC with 50% defect prevalence is 0.75.
    assert abs(c.auc - 0.75) < 1e-9


def test_ties_interpolate_linearly():
    # All PRs share one score: the curve must be the random diagonal,
    # not a favorable accidental ordering.
    scored = [(0.04, True), (0.04, False), (0.04, False), (0.04, False)]
    c = capture_curve(scored)
    assert abs(c.capture_at(0.5) - 0.5) < 1e-9
    assert abs(c.auc - 0.5) < 1e-9


def test_no_defects_yields_empty_curve():
    c = capture_curve([(0.5, False)])
    assert c.auc == 0.0


def test_rule_stats_lift():
    fired = [["a"], ["a"], [], []]
    defects = [True, False, False, False]
    stats = rule_stats(fired, defects)
    assert stats[0].rule == "a"
    assert stats[0].fired == 2
    assert stats[0].precision == 0.5
    assert stats[0].lift == 2.0  # base rate 25%, rule precision 50%
