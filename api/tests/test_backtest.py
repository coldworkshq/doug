# --- harvest checkpoint/resume ----------------------------------------------
# A multi-hour harvest spans GitHub rate windows and can be killed mid-run;
# without incremental checkpoints every interruption re-spends the full quota.


def test_resume_skips_already_enriched(tmp_path, monkeypatch):
    partial = tmp_path / "run.partial.jsonl"
    partial.write_text(json.dumps(_pr(1).model_dump()) + "\n")
    enriched_numbers = []

    async def fake_enrich(gh, owner, repo, pull, sem):
        enriched_numbers.append(pull.number)
        return _pr(pull.number)

    monkeypatch.setattr(harvest_mod, "_enrich", fake_enrich)
    pulls = [SimpleNamespace(number=1), SimpleNamespace(number=2)]
    result = asyncio.run(_enrich_all(None, "o", "r", pulls, partial))

    assert enriched_numbers == [2]  # PR 1 came from the checkpoint, no API spend
    assert [p.number for p in result] == [1, 2]  # listing order preserved
    assert set(_load_partial(partial)) == {1, 2}


def test_progress_survives_mid_run_failure(tmp_path, monkeypatch):
    partial = tmp_path / "run.partial.jsonl"

    async def fake_enrich(gh, owner, repo, pull, sem):
        if pull.number == 2:
            raise RuntimeError("rate limit")
        return _pr(pull.number)

    monkeypatch.setattr(harvest_mod, "_enrich", fake_enrich)
    pulls = [SimpleNamespace(number=1), SimpleNamespace(number=2)]
    with pytest.raises(RuntimeError):
        asyncio.run(_enrich_all(None, "o", "r", pulls, partial))

    assert set(_load_partial(partial)) == {1}  # PR 1's work is not lost


def test_partial_removed_after_final_cache_written(tmp_path, monkeypatch):
    async def fake_harvest(owner, repo, limit, token, before, partial):
        return [_pr(1)]

    monkeypatch.setattr(harvest_mod, "_harvest", fake_harvest)
    stale = tmp_path / "o-r-1.partial.jsonl"
    stale.write_text(json.dumps(_pr(1).model_dump()) + "\n")

    result = harvest_mod.harvest("o", "r", 1, None, tmp_path)

    assert [p.number for p in result] == [1]
    assert (tmp_path / "o-r-1.json").exists()
    assert not stale.exists()  # checkpoint cleaned up once the real cache lands


# --- file-details backfill --------------------------------------------------
# v4 light-diff features need per-file stats + patch text. Old caches predate
# the field; backfill fetches only what's missing, checkpointed like harvest.


def _detail(name: str = "src/a.py") -> FileDetail:
    return FileDetail(filename=name, status="modified", additions=3, deletions=1, patch="@@ -1 +1 @@")


def test_old_cache_loads_with_details_absent(tmp_path):
    (tmp_path / "o-r-1.json").write_text(json.dumps([_pr(1).model_dump(exclude={"file_details"})]))
    result = harvest_mod.harvest("o", "r", 1, None, tmp_path)
    assert result[0].file_details is None  # None = never fetched, [] = fetched-and-empty


def test_backfill_fetches_only_missing(tmp_path, monkeypatch):
    cache = tmp_path / "o-r-2.json"
    done = _pr(1, file_details=[_detail()])
    todo = _pr(2)
    cache.write_text(json.dumps([done.model_dump(), todo.model_dump()]))
    fetched = []

    async def fake_fetch(gh, owner, repo, number, sem):
        fetched.append(number)
        return [_detail("src/b.py")]

    monkeypatch.setattr(harvest_mod, "_fetch_file_details", fake_fetch)
    n = backfill_file_details("o", "r", 2, None, tmp_path)

    assert fetched == [2] and n == 1  # PR 1 already had details, no API spend
    reloaded = harvest_mod.harvest("o", "r", 2, None, tmp_path)
    assert [p.file_details is not None for p in reloaded] == [True, True]
    assert reloaded[1].file_details[0].filename == "src/b.py"
    assert not (tmp_path / "o-r-2.details.jsonl").exists()


def test_backfill_checkpoint_survives_failure(tmp_path, monkeypatch):
    cache = tmp_path / "o-r-2.json"
    original = json.dumps([_pr(1).model_dump(), _pr(2).model_dump()])
    cache.write_text(original)

    async def flaky_fetch(gh, owner, repo, number, sem):
        if number == 2:
            raise RuntimeError("rate limit")
        return [_detail()]

    monkeypatch.setattr(harvest_mod, "_fetch_file_details", flaky_fetch)
    with pytest.raises(RuntimeError):
        backfill_file_details("o", "r", 2, None, tmp_path)

    assert cache.read_text() == original  # money cache untouched on failure
    sidecar = tmp_path / "o-r-2.details.jsonl"
    assert sidecar.exists()  # PR 1's fetch survived

    calls = []

    async def fake_fetch(gh, owner, repo, number, sem):
        calls.append(number)
        return [_detail()]

    monkeypatch.setattr(harvest_mod, "_fetch_file_details", fake_fetch)
    n = backfill_file_details("o", "r", 2, None, tmp_path)
    assert calls == [2]  # PR 1 came from the sidecar — no API re-spend
    assert n == 2  # but both PRs' details landed in the cache this call
    assert all(p.file_details for p in harvest_mod.harvest("o", "r", 2, None, tmp_path))


# --- curve math -------------------------------------------------------------


def test_perfect_separation():
    scored = [(0.9, True), (0.8, True), (0.1, False), (0.1, False)]
    c = capture_curve(scored)
    assert c.capture_at(0.5) == 1.0
    # Max attainable AUC with 50% defect prevalence is 0.75.
    assert abs(c.auc - 0.75) < 1e-9


def test_ties_interpolate_linearly():
    # All PRs share one score: the curve must be the random diagonal,
    # not a favorable accidental ordering.
    scored = [(0.04, True), (0.04, False), (0.04, False), (0.04, False)]
    c = capture_curve(scored)
    assert abs(c.capture_at(0.5) - 0.5) < 1e-9
    assert abs(c.auc - 0.5) < 1e-9


def test_no_defects_yields_empty_curve():
    c = capture_curve([(0.5, False)])
    assert c.auc == 0.0


def test_rule_stats_lift():
    fired = [["a"], ["a"], [], []]
    defects = [True, False, False, False]
    stats = rule_stats(fired, defects)
    assert stats[0].rule == "a"
    assert stats[0].fired == 2
    assert stats[0].precision == 0.5
    assert stats[0].lift == 2.0  # base rate 25%, rule precision 50%
